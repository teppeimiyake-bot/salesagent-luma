/**
 * AI出力の文章体裁ルール（全プロンプト共通）。
 *
 * 社長判断 2026-08：
 *   画面に出る文章が Markdown 記法（# 見出し / - 箇条書き / **強調**）だと視認性が悪い。
 *   日本語のビジネス文書として自然な体裁（■◆の見出し・「・」の箇条書き・「①②③」の順序）で
 *   出力させる。
 *
 * 既存データ・AIが指示を外した場合の保険として、表示側でも @/lib/text-format の
 * toReadableText() が同じ体裁へ整形する（二重にかけても結果は変わらない）。
 */
export const JP_TEXT_STYLE_RULE = `
# 文章の体裁（必ず守る）
- Markdown記法（#、##、**、*、- 、\`）は一切使わない
- 見出しは行頭に「■」（大見出し）／「◆」（中見出し）を置く
- 箇条書きは行頭「・」。入れ子は全角スペース2つのあと「－」
- 手順・優先順位など順序があるものは「①②③」
- 強調は装飾記号ではなく言葉で示す（「最優先で」「必ず」など）
- 意味の切れ目で改行し、1行を長くしすぎない
`.trim();

/**
 * JSON出力プロンプト用（各文字列フィールドの中身に対する体裁ルール）。
 * 見出しは不要なので箇条書き・強調だけに絞る。
 */
export const JP_JSON_TEXT_STYLE_RULE = `
# 各文字列の書き方（必ず守る）
- 文字列の中で Markdown記法（**、#、- ）を使わない
- 1つの文字列に複数項目を入れる場合は「・」で区切る（順序があるものは「①②③」）
`.trim();
