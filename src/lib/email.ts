/**
 * メールアドレスの正規化
 * ============================================================
 * 「ユーザーは存在するのにログインできない」を作らないための共通処理。
 *
 * 背景（実際に起きたこと）:
 *   - users.email は @unique だが、保存される値は入力されたそのまま。
 *     ログインは prisma.user.findUnique({ where: { email } }) の完全一致なので、
 *     大文字小文字・前後の空白・全角文字が1文字でも違えば「Invalid credentials」になる。
 *   - Googleログイン側（src/auth.ts）だけが .toLowerCase().trim() をしており、
 *     パスワードログイン側は素通しだった。同じ人が経路によって別人扱いになりうる。
 *   - 招待テーブルには実際に打ち間違い（luma.official2022@gmail.co）が残っている。
 *     招待の時点で正規化・検証していれば、登録前に気付けた。
 *   - 日本語環境ではIMEがオンのまま全角で入力されることがある（＠ / ｇｍａｉｌ）。
 *     NFKC 正規化で半角に寄せておくと、この種の取り違えを丸ごと潰せる。
 *
 * 方針:
 *   保存時・照合時の両方で必ずこの関数を通す。片方だけに入れると、
 *   「登録はできたがログインできない」という最悪の非対称が生まれる。
 */

/** 半角/全角スペース・タブ・改行・ゼロ幅スペース */
const BLANK_RE = /[\s　​-‍﻿]/g;

/**
 * メールアドレスを照合可能な正規形にする。
 * - NFKC で全角英数字・全角＠を半角へ
 * - 空白文字（全角スペース・ゼロ幅含む）を除去
 * - 小文字化
 *
 * 注意: ローカル部の大文字小文字を区別するメールサーバーも規格上は存在するが、
 * 本システムの利用者は Google Workspace（大文字小文字を区別しない）のため
 * 小文字化して困る相手はいない。取り違え防止の利益が上回る。
 */
export function normalizeEmail(input: string): string {
  return input.normalize("NFKC").replace(BLANK_RE, "").toLowerCase();
}
