import { createServer } from "http";
import { writeFileSync } from "fs";
import { join } from "path";
import { randomUUID } from "crypto";
import { loadEnvConfig } from "@next/env";
import { google } from "googleapis";
import { MEET_OAUTH_SCOPES } from "../src/lib/google/meet-artifacts";

loadEnvConfig(process.cwd());

const PORT = 3333;
const REDIRECT_URI = `http://localhost:${PORT}/oauth2callback`;
// スコープの正はライブラリ側（src/lib/google/meet-artifacts.ts）に一本化する。
const SCOPES = MEET_OAUTH_SCOPES;
const OUTPUT_FILE = ".env.meet.local";

const clientId = process.env.GOOGLE_MEET_CLIENT_ID;
const clientSecret = process.env.GOOGLE_MEET_CLIENT_SECRET;

if (!clientId || !clientSecret) {
  console.error("Missing GOOGLE_MEET_CLIENT_ID or GOOGLE_MEET_CLIENT_SECRET in local .env.");
  process.exit(1);
}

const oauth2Client = new google.auth.OAuth2(clientId, clientSecret, REDIRECT_URI);
const state = randomUUID();
const authUrl = oauth2Client.generateAuthUrl({
  access_type: "offline",
  prompt: "consent",
  scope: SCOPES,
  state,
});

const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url ?? "/", REDIRECT_URI);
    if (url.pathname !== "/oauth2callback") {
      res.writeHead(404);
      res.end("Not found");
      return;
    }

    if (url.searchParams.get("state") !== state) {
      res.writeHead(400);
      res.end("Invalid state.");
      return;
    }

    const code = url.searchParams.get("code");
    if (!code) {
      res.writeHead(400);
      res.end("Missing code.");
      return;
    }

    const { tokens } = await oauth2Client.getToken(code);
    if (!tokens.refresh_token) {
      res.writeHead(400);
      res.end("No refresh token returned. Re-run after removing prior consent or keep prompt=consent.");
      return;
    }

    const outputPath = join(process.cwd(), OUTPUT_FILE);
    writeFileSync(
      outputPath,
      `# Generated by scripts/google-meet-auth.ts\nGOOGLE_MEET_REFRESH_TOKEN="${tokens.refresh_token}"\n`,
      { encoding: "utf8", flag: "w" },
    );

    res.writeHead(200, { "Content-Type": "text/plain; charset=utf-8" });
    res.end(`Refresh token generated. Check ${OUTPUT_FILE} and add it to your local .env.`);
    console.log(`Refresh token generated and written to ${OUTPUT_FILE}.`);
    console.log("");
    console.log("【注意】Meetのスコープ（meetings.space.*）を追加したため（drive.readonly は2026-09-30に外した）、");
    console.log("      これまでのリフレッシュトークンでは自動録画・自動文字起こしの設定はできません。");
    console.log("      再同意で発行した今回のトークンが旧トークンを置き換えます。");
    console.log("      GOOGLE_MEET_REFRESH_TOKEN を .env / Vercel の環境変数にも反映してください。");
  } catch (error) {
    res.writeHead(500);
    res.end("Token exchange failed. Check the terminal output.");
    console.error(error instanceof Error ? error.message : String(error));
  } finally {
    server.close();
  }
});

server.listen(PORT, () => {
  console.log(`Listening on ${REDIRECT_URI}`);
  console.log("Open this URL in the Google test account browser:");
  console.log(authUrl);
});
